def _clean_rest(rest: str) -> str:
    """
    Чистит rest для отображения в объяснении.

    Логика:
      1) срезаем трейлинг ':;{, '
      2) срезаем ЛИШНИЕ закрывающие ) в конце (Rust println! etc.)
      3) если вся строка — парная '( ... )' — раскрываем
      4) если вся строка — парная '{ ... }' — раскрываем
    """
    rest = rest.strip()

    # 1) трейлинг
    while rest and rest[-1] in ":;{, ":
        rest = rest[:-1].rstrip()

    # 2) НОВОЕ: срезать лишние ) в конце
    if rest.endswith(")"):
        opens = rest.count("(")
        closes = rest.count(")")
        while closes > opens and rest.endswith(")"):
            rest = rest[:-1].rstrip()
            closes -= 1

    # 3) парные ( ) вокруг всего
    if rest.startswith("(") and rest.endswith(")"):
        depth = 0
        ok = True
        for i, ch in enumerate(rest):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0 and i < len(rest) - 1:
                    ok = False
                    break
        if ok and depth == 0:
            rest = rest[1:-1].strip()

    # 4) парные { } вокруг всего
    if rest.startswith("{") and rest.endswith("}"):
        depth = 0
        ok = True
        for i, ch in enumerate(rest):
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0 and i < len(rest) - 1:
                    ok = False
                    break
        if ok and depth == 0:
            rest = rest[1:-1].strip()

    if len(rest) > 40:
        rest = rest[:37] + "..."
    return rest or "…"


def _detect_kind(lang_name: str, stripped: str):
    # 1) Brainfuck — посимвольно
    if lang_name == "brainfuck":
        chars = [c for c in stripped if c in BF_COMMANDS]
        if not chars:
            return ("—", "")
        # Группируем подряд идущие одинаковые
        groups = []
        prev = chars[0]
        n = 1
        for c in chars[1:]:
            if c == prev:
                n += 1
            else:
                groups.append((prev, n))
                prev = c
                n = 1
        groups.append((prev, n))
        # Опишем первые 3 группы
        descr = []
        for c, n in groups[:3]:
            cat, txt = BF_COMMANDS[c]
            descr.append(f"{txt}" + (f"×{n}" if n > 1 else ""))
        return ("bf-команды", "; ".join(descr))

    # 2) Whitespace — по символам
    if lang_name == "whitespace":
        parts = []
        for c in stripped:
            if c in WS_CHARS:
                parts.append(WS_CHARS[c])
        if not parts:
            return ("—", "")
        uniq = []
        for p in parts:
            if not uniq or uniq[-1] != p:
                uniq.append(p)
        return ("ws-команды", " → ".join(uniq[:5]))

    # 3) Rivulet — по глифам
    if lang_name == "rivulet":
        glyphs = [c for c in stripped if c in RIVULET_GLYPHS]
        if glyphs:
            names = [RIVULET_GLYPHS[c] for c in glyphs[:3]]
            return ("rivulet-глифы", "; ".join(names))
        if stripped.strip():
            return ("rivulet-текст", "текст без глифов")
        return ("—", "")

    # 4) Комментарии (для языков, где # — комментарий, или // -- ; и т.д.)
    if lang_name in HASH_COMMENT_LANGS and stripped.startswith("#"):
        return ("комментарий", "Комментарий — игнорируется")
    for p in COMMENT_PREFIXES:
        if stripped.startswith(p):
            return ("комментарий", "Комментарий — игнорируется")

    # 5) Ключевые слова языка (по длине — от длинных к коротким)
    kws = KEYWORDS.get(lang_name, {})
    for kw in sorted(kws.keys(), key=len, reverse=True):
        cat, tmpl = kws[kw]
        pat = re.escape(kw)
        m = re.search(rf"(?:^|\s|\()({pat})(?:\b|\()", stripped)
        if m:
            rest = stripped[m.end():]
            rest = _clean_rest(rest)
            text = tmpl.replace("{rest}", rest)
            return (cat, text)

    # 6) Универсальные ключевые слова
    for pat, cat, text in GENERIC:
        if re.search(pat, stripped):
            return (cat, text)

    # 7) Присваивание
    if re.search(r"^[A-Za-z_$][A-Za-z0-9_$]*\s*(=|:=|<-)", stripped):
        return ("перемен.", "Присваивание или объявление")

    # 8) Операции
    for pat, cat, text in OPERATIONS:
        if re.search(pat, stripped):
            return (cat, text)

    # 9) Вызов функции
    if re.search(r"\w+\s*\(.*\)\s*;?\s*$", stripped):
        return ("вызов", "Вызов функции")

    # 10) Скобки блока
    if stripped in ("{", "}"):
        return ("блок", "Граница блока кода")
    if stripped in ("(", ")"):
        return ("блок", "Граница выражения")

    # 11) Литералы
    if re.match(r"^[\d\.]+$", stripped):
        return ("литерал", "Числовой литерал")
    if re.match(r"^['\"].*['\"]$", stripped):
        return ("литерал", "Строковый литерал")

    return ("—", "")


