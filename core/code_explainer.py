def explain(lang_name: str, code: str) -> list[dict]:
    if not isinstance(code, str):
        return []
    out = []
    for i, line in enumerate(code.splitlines(), 1):
        stripped = line.strip()
        if not stripped:
            out.append({"n": i, "line": line, "kind": "пусто", "text": ""})
            continue
        kind, text = _detect_kind(lang_name, stripped)
        out.append({"n": i, "line": line, "kind": kind, "text": text})
    return out


def explain_text(lang_name: str, code: str) -> str:
    rows = explain(lang_name, code)
    if not rows:
        return "(пусто)"
    max_n = max(len(str(r["n"])) for r in rows)
    lines = []
    for r in rows:
        num = str(r["n"]).rjust(max_n)
        lines.append(f" {num}  {r['line'].rstrip()}")
        if r["kind"] != "пусто" and r["text"]:
            lines.append(f" {' ' * max_n}      ← {r['kind']}: {r['text']}")
    return "\n".join(lines)


